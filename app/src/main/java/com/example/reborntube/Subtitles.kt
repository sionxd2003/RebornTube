package com.example.reborntube

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import java.net.HttpURLConnection
import java.net.URL

/** Una línea de subtítulos con su tiempo (milisegundos). */
data class Cue(val startMs: Long, val endMs: Long, val text: String)

/**
 * Los subtítulos se descargan y se dibujan encima del vídeo (como hace NewPipe), en vez de pasarlos
 * por ExoPlayer, que daba error de reproducción al mezclarlos con el vídeo y el audio.
 */
object SubtitleLoader {
    suspend fun load(stream: SubtitlesStream): List<Cue> = withContext(Dispatchers.IO) {
        val conn = URL(stream.content).openConnection() as HttpURLConnection
        conn.connectTimeout = 15000
        conn.readTimeout = 15000
        conn.setRequestProperty("User-Agent", DownloaderImpl.USER_AGENT)
        val text = conn.inputStream.bufferedReader().use { it.readText() }
        val cues = if (text.trimStart().startsWith("WEBVTT") || stream.format == MediaFormat.VTT) {
            parseVtt(text)
        } else {
            parseTtml(text)
        }
        val sorted = cues.sortedBy { it.startMs }
        if (stream.isAutoGenerated) dedupe(sorted) else sorted
    }
}

/** Texto que toca mostrar en ese momento (o null). */
fun cueAt(cues: List<Cue>, positionMs: Long): String? {
    var lo = 0
    var hi = cues.size - 1
    var index = -1
    while (lo <= hi) {
        val mid = (lo + hi) ushr 1
        if (cues[mid].startMs <= positionMs) {
            index = mid
            lo = mid + 1
        } else {
            hi = mid - 1
        }
    }
    var i = index
    var steps = 0
    while (i >= 0 && steps < 4) {
        if (positionMs < cues[i].endMs) return cues[i].text
        i--
        steps++
    }
    return null
}

private val vttTime = Regex(
    "((?:\\d+:)?\\d{1,2}:\\d{2}[.,]\\d{1,3})\\s*-->\\s*((?:\\d+:)?\\d{1,2}:\\d{2}[.,]\\d{1,3})"
)

private fun parseVtt(text: String): List<Cue> {
    val cues = ArrayList<Cue>()
    val blocks = text.replace("\r\n", "\n").split(Regex("\n\n+"))
    for (block in blocks) {
        val lines = block.split("\n")
        val idx = lines.indexOfFirst { vttTime.containsMatchIn(it) }
        if (idx < 0) continue
        val m = vttTime.find(lines[idx]) ?: continue
        val start = parseClock(m.groupValues[1])
        val end = parseClock(m.groupValues[2])
        val body = cleanText(lines.drop(idx + 1).joinToString("\n"))
        if (body.isNotEmpty() && end > start) cues += Cue(start, end, body)
    }
    return cues
}

private fun parseTtml(text: String): List<Cue> {
    val cues = ArrayList<Cue>()
    val paragraph = Regex("<p\\b([^>]*)>(.*?)</p>", RegexOption.DOT_MATCHES_ALL)
    for (m in paragraph.findAll(text)) {
        val attrs = m.groupValues[1]
        val begin = attr(attrs, "begin")
        val end = attr(attrs, "end")
        val dur = attr(attrs, "dur")
        val t = attr(attrs, "t")
        val d = attr(attrs, "d")
        val start: Long
        val finish: Long
        if (begin != null) {
            start = parseTtmlTime(begin)
            finish = if (end != null) parseTtmlTime(end) else start + (dur?.let { parseTtmlTime(it) } ?: 0L)
        } else if (t != null) {
            start = t.toLongOrNull() ?: continue
            finish = start + (d?.toLongOrNull() ?: 0L)
        } else {
            continue
        }
        val body = cleanText(m.groupValues[2].replace(Regex("<br\\s*/?>"), "\n"))
        if (body.isNotEmpty() && finish > start) cues += Cue(start, finish, body)
    }
    return cues
}

private fun attr(attrs: String, name: String): String? =
    Regex("\\b$name=\"([^\"]*)\"").find(attrs)?.groupValues?.get(1)

private fun parseClock(s: String): Long {
    val parts = s.replace(',', '.').split(":")
    val seconds = parts.last().toDouble()
    val minutes = if (parts.size >= 2) parts[parts.size - 2].toLong() else 0L
    val hours = if (parts.size >= 3) parts[parts.size - 3].toLong() else 0L
    return (hours * 3600 + minutes * 60) * 1000 + (seconds * 1000).toLong()
}

private fun parseTtmlTime(s: String): Long = when {
    s.contains(":") -> parseClock(s)
    s.endsWith("ms") -> s.dropLast(2).toDouble().toLong()
    s.endsWith("s") -> (s.dropLast(1).toDouble() * 1000).toLong()
    else -> s.toDouble().toLong()
}

private fun cleanText(raw: String): String {
    var s = raw.replace(Regex("<[^>]+>"), "")
    s = s.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
        .replace("&quot;", "\"").replace("&#39;", "'").replace("&apos;", "'").replace("&nbsp;", " ")
    return s.split("\n").map { it.trim() }.filter { it.isNotEmpty() }.joinToString("\n")
}

/** Los subtítulos automáticos de YouTube repiten la línea anterior en cada paso: se quitan los repetidos. */
private fun dedupe(cues: List<Cue>): List<Cue> {
    val out = ArrayList<Cue>()
    var previous = emptySet<String>()
    for (c in cues) {
        if (c.endMs - c.startMs < 80) continue
        val lines = c.text.split("\n")
        val fresh = lines.filter { it !in previous }
        previous = lines.toSet()
        if (fresh.isEmpty()) continue
        out += Cue(c.startMs, c.endMs, fresh.joinToString("\n"))
    }
    return out
}
